export function categorizeMenuItem(itemName: string): MenuCategory {
  if (!itemName || typeof itemName !== 'string') {
    return 'entrees';
  }

  const lowerItemName = itemName.toLowerCase();

  for (const mapping of CATEGORY_MAPPINGS) {
    for (const keyword of mapping.keywords) {
      if (lowerItemName.includes(keyword.toLowerCase())) {
        return mapping.category;
      }
    }
  }

  return 'entrees';
}

export function categorizeMenuItems(
  items: string[],
): Array<{ name: string; category: MenuCategory }> {
  return items.map((item) => ({
    name: item,
    category: categorizeMenuItem(item),
  }));
}
