export function isEventBlocked(event: CalendarData): boolean {
  const title = event.calendarTitle ?? '';
  const description = event.calendarDescription ?? '';
  const category = event.calendarCategory ?? '';
  const combined = `${title} ${description} ${category}`.toLowerCase();

  return HARD_BLOCK_PATTERNS.some((pattern) => pattern.test(combined));
}
